function is_deadlock = is_experiment_deadlocked(experiment_result)
    % IS_DEADLOCK checks if a deadlock occurs in the experiment_result
    % A deadlock occurs if all vehicles in a subgraph have stopped for two consecutive time steps.
    % If a deadlock occurs, the function returns true. Otherwise, it returns false.

    arguments
        experiment_result (1, 1) ExperimentResult
    end

    % deadlock if no priority assignment allows any stopped vehicle to move
    is_deadlock = false;

    if experiment_result.hlc_indices == -1
        return;
    end

    stop_tolerance = 1e-9;
    movement_tolerance = 1e-6;

    options = experiment_result.options;
    mpa = MotionPrimitiveAutomaton(options);
    optimizer = OptimizerInterface.get_optimizer(options);

    [vehicle_lengths, vehicle_widths, static_obstacles, scenario] = load_scenario_geometry(options);

    for k = 1:experiment_result.n_steps
        % vehicle is stopped if the predicted (x, y, yaw) equals x0 for the full horizon
        y_predicted = experiment_result.get_y_predicted(k); % 3 x Hp x nVeh
        x0 = experiment_result.iteration_data(k).x0(:, 1:3)'; % 3 x nVeh
        x0_over_horizon = repmat(reshape(x0, 3, 1, []), 1, size(y_predicted, 2), 1);
        is_vehicle_stopped = squeeze(all(all(abs(y_predicted - x0_over_horizon) <= stop_tolerance, 1), 2));
        is_vehicle_stopped = reshape(is_vehicle_stopped, [], 1);

        iter_k = experiment_result.iteration_data(k);

        % find vehicle groups: connected subgraphs
        groups = conncomp(digraph(iter_k.directed_coupling_sequential(:, :, 1)), Type = 'weak');
        n_groups = max(groups);

        for i_group = 1:n_groups
            % Potential deadlock if two vehicles in a group stopped
            group_vehicle_indices = find(groups == i_group);
            stopped_vehicles_in_group = is_vehicle_stopped(group_vehicle_indices);
            is_potential_deadlock = sum(stopped_vehicles_in_group) >= 2;

            if is_potential_deadlock

                if sum(stopped_vehicles_in_group) >= 7
                    % if 7 or more vehicles are stopped, we assume deadlock to avoid combinatorial explosion of priority permutations
                    disp('Assuming deadlock due to large number of stopped vehicles in group');
                    is_deadlock = true;
                    return;
                end

                stopped_vehicle_indices = group_vehicle_indices(stopped_vehicles_in_group);

                % if priority strategy is constant or coloring, only consider current priority
                % otherwise, consider all prioritizations for the stopped vehicles
                priorities_to_test = get_priorities_to_test(iter_k, stopped_vehicle_indices, options.priority);

                is_any_permutation_feasible = false;

                for i_priority = 1:size(priorities_to_test, 2)

                    if is_stopped_group_feasible( ...
                            stopped_vehicle_indices, ...
                            priorities_to_test(:, i_priority), ...
                            iter_k, ...
                            options, ...
                            optimizer, ...
                            mpa, ...
                            vehicle_lengths, ...
                            vehicle_widths, ...
                            static_obstacles, ...
                            scenario, ...
                            k, ...
                            movement_tolerance ...
                        )
                        is_any_permutation_feasible = true;
                        break;
                    end

                end

                % if no feasible plan exists, deadlock occurs
                if ~is_any_permutation_feasible
                    is_deadlock = true;
                    return;
                end

            end

        end

    end

end

function priorities_to_test = get_priorities_to_test(iter_k, stopped_vehicle_indices, priority_strategy)

    adjacency_stopped = iter_k.adjacency(stopped_vehicle_indices, stopped_vehicle_indices);

    switch priority_strategy
        case {PriorityStrategies.constant_priority, PriorityStrategies.coloring_priority}
            directed_current = iter_k.directed_coupling(stopped_vehicle_indices, stopped_vehicle_indices);
            current_priorities = Prioritizer.priorities_from_directed_coupling(directed_current);

            if any(current_priorities == 0)
                current_priorities = 1:length(stopped_vehicle_indices);
            end

            priorities_to_test = current_priorities(:);
        otherwise
            priorities_to_test = Prioritizer.unique_priorities(adjacency_stopped);

            if isempty(priorities_to_test)
                priorities_to_test = (1:length(stopped_vehicle_indices))';
            end

    end

end

function is_feasible = is_stopped_group_feasible( ...
        stopped_vehicle_indices, ...
        priorities, ...
        iter_k, ...
        options, ...
        optimizer, ...
        mpa, ...
        vehicle_lengths, ...
        vehicle_widths, ...
        static_obstacles, ...
        scenario, ...
        time_step, ...
        movement_tolerance ...
    )

    order = planning_order_from_priorities(priorities);
    ordered_vehicle_indices = stopped_vehicle_indices(order);

    dynamic_obstacles_from_predecessors = cell(0, options.Hp);
    is_feasible = false;

    for i_order = 1:length(ordered_vehicle_indices)
        i_vehicle = ordered_vehicle_indices(i_order);
        successor_vehicle_indices = ordered_vehicle_indices(i_order + 1:end);

        iter_single = build_single_vehicle_iter( ...
            i_vehicle, ...
            successor_vehicle_indices, ...
            iter_k, ...
            options, ...
            mpa, ...
            vehicle_lengths, ...
            vehicle_widths, ...
            static_obstacles, ...
            scenario, ...
            dynamic_obstacles_from_predecessors ...
        );

        info = optimizer.run_optimizer(1, iter_single, mpa, options, time_step);

        if info.is_exhausted || isempty(info.shapes)
            info.shapes = standstill_shapes_from_current_pose( ...
                iter_single.x0(1, 1), ...
                iter_single.x0(1, 2), ...
                iter_single.x0(1, 3), ...
                vehicle_lengths(i_vehicle), ...
                vehicle_widths(i_vehicle), ...
                options.offset, ...
                options.Hp ...
            );
        end

        if ~info.is_exhausted && has_vehicle_moved(info, iter_single.x0(1, 1:3), movement_tolerance)
            is_feasible = true;
            return;
        end

        if ~isempty(info.shapes)
            dynamic_obstacles_from_predecessors(end + 1, :) = info.shapes(1, :); %#ok<AGROW>
        end

    end

end

function shapes = standstill_shapes_from_current_pose( ...
        x, ...
        y, ...
        yaw, ...
        vehicle_length, ...
        vehicle_width, ...
        offset, ...
        prediction_horizon ...
    )

    occupied = get_occupied_areas( ...
        x, ...
        y, ...
        yaw, ...
        vehicle_length, ...
        vehicle_width, ...
        offset ...
    );
    standstill_shape = occupied.normal_offset;
    shapes = repmat({standstill_shape}, 1, prediction_horizon);

end

function order = planning_order_from_priorities(priorities)
    [~, order] = sort(priorities(:), 'ascend');
end

function iter_single = build_single_vehicle_iter( ...
        i_vehicle, ...
        successor_vehicle_indices, ...
        iter_k, ...
        options, ...
        mpa, ...
        vehicle_lengths, ...
        vehicle_widths, ...
        static_obstacles, ...
        scenario, ...
        dynamic_obstacles_from_predecessors ...
    )

    iter_for_filter = prepare_iter_for_filter(iter_k, options);
    vehicle_filter = false(1, iter_for_filter.amount);
    vehicle_filter(i_vehicle) = true;
    iter_single = IterationData.filter(iter_for_filter, vehicle_filter);

    occupied_successor_vehicles = build_current_occupied_areas( ...
        successor_vehicle_indices, ...
        iter_k, ...
        vehicle_lengths, ...
        vehicle_widths, ...
        options.offset ...
    );

    iter_single.obstacles = [static_obstacles(:); occupied_successor_vehicles(:)];
    iter_single.dynamic_obstacle_area = dynamic_obstacles_from_predecessors;
    iter_single.predicted_lanelet_boundary = reconstruct_predicted_lanelet_boundary( ...
        i_vehicle, ...
        iter_single, ...
        options, ...
        mpa, ...
        scenario ...
    );
    iter_single.hdv_reachable_sets = cell(0, options.Hp);
    iter_single.hdv_adjacency = false(1, 0);

end

function predicted_lanelet_boundary = reconstruct_predicted_lanelet_boundary( ...
        i_vehicle, ...
        iter_single, ...
        options, ...
        mpa, ...
        scenario ...
    )

    predicted_lanelet_boundary = cell(1, 3);

    if options.scenario_type == ScenarioType.circle
        return;
    end

    if isempty(scenario) || i_vehicle > numel(scenario.vehicles)
        return;
    end

    try
        vehicle = scenario.vehicles(i_vehicle);

        [reference_trajectory_struct, ~, current_point_index] = get_reference_trajectory( ...
            mpa, ...
            vehicle.reference_path, ...
            vehicle.reference_speed, ...
            iter_single.x0(1, 1), ...
            iter_single.x0(1, 2), ...
            iter_single.trim_indices(1), ...
            options.dt_seconds ...
        );

        [predicted_lanelets, ~] = get_predicted_lanelets( ...
            vehicle.reference_path, ...
            vehicle.points_index, ...
            vehicle.lanelets_index, ...
            reference_trajectory_struct, ...
            current_point_index ...
        );

        predicted_lanelet_boundary = get_lanelets_boundary( ...
            predicted_lanelets, ...
            scenario.lanelet_boundary, ...
            vehicle.lanelets_index, ...
            vehicle.is_loop ...
        );
    catch exception
        predicted_lanelet_boundary = cell(1, 3);
        warning( ...
            'Failed to reconstruct predicted lanelet boundary for vehicle %d. Setting it to empty. Error: %s', ...
            i_vehicle, ...
            exception.message ...
        );
    end

end

function iter_for_filter = prepare_iter_for_filter(iter_k, options)

    iter_for_filter = iter_k;
    n_vehicles = iter_k.amount;

    if isempty(iter_for_filter.v_ref)
        iter_for_filter.v_ref = zeros(n_vehicles, options.Hp);
    end

    if isempty(iter_for_filter.predicted_lanelets)
        iter_for_filter.predicted_lanelets = cell(n_vehicles, 1);
    end

    if isempty(iter_for_filter.predicted_lanelet_boundary)
        iter_for_filter.predicted_lanelet_boundary = cell(n_vehicles, 3);
    end

    if isempty(iter_for_filter.reachable_sets)
        iter_for_filter.reachable_sets = cell(n_vehicles, options.Hp);
    end

    if isempty(iter_for_filter.hdv_adjacency)
        iter_for_filter.hdv_adjacency = false(n_vehicles, 0);
    end

end

function occupied_areas = build_current_occupied_areas( ...
        vehicle_indices, ...
        iter_k, ...
        vehicle_lengths, ...
        vehicle_widths, ...
        offset ...
    )

    occupied_areas = cell(length(vehicle_indices), 1);

    for i_idx = 1:length(vehicle_indices)
        i_vehicle = vehicle_indices(i_idx);
        occupied = get_occupied_areas( ...
            iter_k.x0(i_vehicle, 1), ...
            iter_k.x0(i_vehicle, 2), ...
            iter_k.x0(i_vehicle, 3), ...
            vehicle_lengths(i_vehicle), ...
            vehicle_widths(i_vehicle), ...
            offset ...
        );
        occupied_areas{i_idx} = occupied.normal_offset;
    end

end

function moved = has_vehicle_moved(info, x0_pose, movement_tolerance)

    if isempty(info.y_predicted)
        moved = false;
        return;
    end

    y_predicted = info.y_predicted(:, :, 1);
    x0_pose = x0_pose(:);
    x0_over_horizon = repmat(x0_pose, 1, size(y_predicted, 2));

    moved = any(any(abs(y_predicted - x0_over_horizon) > movement_tolerance, 1), 2);
    moved = logical(moved);

end

function [vehicle_lengths, vehicle_widths, static_obstacles, scenario] = load_scenario_geometry(options)

    default_length = 0.22;
    default_width = 0.1;

    vehicle_lengths = default_length * ones(options.amount, 1);
    vehicle_widths = default_width * ones(options.amount, 1);
    static_obstacles = {};
    scenario = [];

    try
        scenario = Scenario.create(options);

        n_scenario_vehicles = min(length(scenario.vehicles), options.amount);

        for i_vehicle = 1:n_scenario_vehicles
            vehicle_lengths(i_vehicle) = scenario.vehicles(i_vehicle).Length;
            vehicle_widths(i_vehicle) = scenario.vehicles(i_vehicle).Width;
        end

        static_obstacles = scenario.obstacles;
    catch
        % fall back to default geometry and no static obstacles
    end

end
